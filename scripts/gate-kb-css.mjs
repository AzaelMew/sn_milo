#!/usr/bin/env node
// Deterministic KB dark-mode CSS gate (no dependencies; small hand parser, tested in tests/kb-css-gate.test.mjs).
//
//   node scripts/gate-kb-css.mjs          regenerate features/kb-dark/dark.css from the original stylesheet
//   node scripts/gate-kb-css.mjs --check  fail if the committed output differs (no writes)
//
// Input: features/kb-dark/source/dark.original.css (the unmodified original stylesheet, servicenow-kb-dark 1.0.1).
// Every selector of every style rule gets the zero-specificity gate  :where(:root:not([data-milo-kb-off]))
//   - first compound matches the root element (type `html` or contains `:root`): the gate is CONJOINED with that
//     compound (before any pseudo-element), e.g. `html body p` → `html:where(…) body p`, `:root` → `:root:where(…)`.
//     Prepending would add an ancestor the root element can never have.
//   - first compound has a type selector other than `html` (cannot be the root of an HTML document): the gate is
//     PREPENDED as an ancestor plus a descendant combinator, e.g. `p::placeholder` → `:where(…) p::placeholder`.
//   - anything else (`.x`, `#id`, `*`, `[attr]`, `:not(…)`, `::selection`, `:host` first) could match the root OR a
//     descendant; the transformer refuses instead of guessing (review by hand).
// Each selector-list branch is handled separately; declarations, comments, whitespace and rule order are copied
// byte-for-byte. @media/@supports/@container/@layer/@document blocks are recursed into; @keyframes, @font-face and
// other selector-free at-rules are copied verbatim; @import (its sheet would stay ungated), any other block at-rule
// (e.g. @scope), CSS nesting inside a style rule, and a namespace prefix (`|`) or escape (`\`) in a first compound
// are rejected. Unquoted url(...) tokens in declarations are skipped as literals, so braces inside them are not
// mistaken for nesting. Specificity is unchanged because the whole addition sits inside :where().
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

export const OFF_ATTRIBUTE = 'data-milo-kb-off';
export const GATE = `:where(:root:not([${OFF_ATTRIBUTE}]))`;
export const ORIGINAL = 'features/kb-dark/source/dark.original.css';
export const OUTPUT = 'features/kb-dark/dark.css';
/** Every gated sheet: one source stylesheet → one committed output. The first entry is the original sheet. */
export const SHEETS = Object.freeze([
  {source: ORIGINAL, output: OUTPUT, note: 'servicenow-kb-dark 1.0.1'},
  {source: 'features/kb-dark/source/tcp.extra.css', output: 'features/kb-dark/dark-tcp.css',
   note: 'sn_milo additions for the Time Sheet Portal (/tcp)'}
]);
export const headerFor = ({source, note}) => `/* GENERATED by scripts/gate-kb-css.mjs from ${source} (${note}). Do not edit.
   sn_milo: every selector is gated by the zero-specificity ${GATE};
   features/kb-dark/content.js sets ${OFF_ATTRIBUTE} on <html> when KB dark mode is off. */
`;
export const HEADER = headerFor(SHEETS[0]);

const GROUPING = new Set(['media', 'supports', 'container', 'layer', 'document', '-moz-document']);
const OPAQUE = new Set(['keyframes', '-webkit-keyframes', 'font-face', 'page', 'property', 'counter-style',
  'font-feature-values', 'font-palette-values', 'viewport', '-ms-viewport']);
const LEGACY_PSEUDO_ELEMENTS = /^:(before|after|first-line|first-letter)(?![-\w])/i;

/** Index just after a string starting at i (s[i] is the quote). */
function skipString(s, i) {
  const q = s[i];
  for (let j = i + 1; j < s.length; j++) {
    if (s[j] === '\\') { j++; continue; }
    if (s[j] === q) return j + 1;
    if (s[j] === '\n') throw new Error(`unterminated string at ${i}`);
  }
  throw new Error(`unterminated string at ${i}`);
}
/** Index just after an UNQUOTED url(...) token starting at i, or -1 if s[i] does not start one (a quoted url( is
 *  an ordinary function whose string argument the callers skip anyway). Its contents ({ } ; etc.) are literal. */
function skipUrl(s, i) {
  if (!/^url\(/i.test(s.slice(i, i + 4)) || (i > 0 && /[-\w\\]/.test(s[i - 1]))) return -1;
  let j = i + 4;
  while (j < s.length && /\s/.test(s[j])) j++;
  if (s[j] === '"' || s[j] === "'") return -1;
  for (; j < s.length; j++) {
    if (s[j] === '\\') { j++; continue; }
    if (s[j] === ')') return j + 1;
  }
  throw new Error(`unterminated url( at ${i}`);
}
function skipComment(s, i) {
  const end = s.indexOf('*/', i + 2);
  if (end < 0) throw new Error(`unterminated comment at ${i}`);
  return end + 2;
}

/** Split at top-level occurrences of `sep` (outside strings, comments, (), []). Separators are dropped; the
 *  pieces keep their own whitespace, so pieces.join(sep) === input. */
export function splitTopLevel(s, sep) {
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < s.length;) {
    const ch = s[i];
    if (ch === '\\') { i += 2; continue; }
    if (ch === '"' || ch === "'") { i = skipString(s, i); continue; }
    if (ch === '/' && s[i + 1] === '*') { i = skipComment(s, i); continue; }
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth--;
    else if (ch === sep && depth === 0) { out.push(s.slice(start, i)); start = i + 1; }
    i++;
  }
  out.push(s.slice(start));
  return out;
}

/** End index of the first compound selector of a complex selector (first top-level whitespace or combinator). */
function firstCompoundEnd(s) {
  let depth = 0;
  for (let i = 0; i < s.length;) {
    const ch = s[i];
    if (ch === '\\') { i += 2; continue; }
    if (ch === '"' || ch === "'") { i = skipString(s, i); continue; }
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth--;
    else if (depth === 0 && /[\s>+~]/.test(ch)) return i;
    i++;
  }
  return s.length;
}

/** Top-level pseudo-class names of a compound, and the index of its first pseudo-element (or -1). */
function inspectCompound(c) {
  const pseudoClasses = [];
  let pseudoElementAt = -1;
  let depth = 0;
  for (let i = 0; i < c.length;) {
    const ch = c[i];
    if (ch === '\\') { i += 2; continue; }
    if (ch === '"' || ch === "'") { i = skipString(c, i); continue; }
    if (ch === '(' || ch === '[') { depth++; i++; continue; }
    if (ch === ')' || ch === ']') { depth--; i++; continue; }
    if (depth === 0 && ch === ':') {
      if (c[i + 1] === ':' || LEGACY_PSEUDO_ELEMENTS.test(c.slice(i))) { if (pseudoElementAt < 0) pseudoElementAt = i; i += 2; continue; }
      const m = /^:(-?[_a-zA-Z][-\w]*)/.exec(c.slice(i));
      if (m) { pseudoClasses.push(m[1].toLowerCase()); i += m[0].length; continue; }
    }
    i++;
  }
  return {pseudoClasses, pseudoElementAt};
}

function gateBranch(sel) {
  const end = firstCompoundEnd(sel);
  const compound = sel.slice(0, end);
  const rest = sel.slice(end);
  // A namespace prefix (ns|html, *|html, |html — or `|=` in an attribute) or any CSS escape (html\:x, :ro\6f t)
  // in the first compound defeats the simple type/:root reading below; refuse rather than misjudge the root.
  if (compound.includes('|')) throw new Error(`namespace (|) in first compound ${JSON.stringify(compound)} of ${JSON.stringify(sel)} not supported; gate it by hand`);
  if (compound.includes('\\')) throw new Error(`escape (\\) in first compound ${JSON.stringify(compound)} of ${JSON.stringify(sel)} not supported; gate it by hand`);
  const type = /^(-?[_a-zA-Z][-\w]*)/.exec(compound)?.[1];
  const {pseudoClasses, pseudoElementAt} = inspectCompound(compound);
  const isRoot = (type && type.toLowerCase() === 'html') || pseudoClasses.includes('root');
  if (isRoot) {
    const at = pseudoElementAt < 0 ? compound.length : pseudoElementAt;
    return compound.slice(0, at) + GATE + compound.slice(at) + rest;
  }
  if (type) return `${GATE} ${sel}`;
  throw new Error(`cannot decide whether ${JSON.stringify(compound)} (first compound of ${JSON.stringify(sel)}) can match the root element; gate it by hand`);
}

/** Gate one selector list; each branch keeps its surrounding whitespace. */
export function gateSelector(selector) {
  if (selector.includes(GATE)) throw new Error(`selector already gated: ${selector}`);
  if (/\/\*/.test(selector)) throw new Error(`comment inside selector not supported: ${selector}`);
  return splitTopLevel(selector, ',').map(branch => {
    const lead = /^\s*/.exec(branch)[0];
    const trail = /\s*$/.exec(branch)[0];
    const core = branch.slice(lead.length, branch.length - trail.length);
    if (!core) throw new Error(`empty selector in ${JSON.stringify(selector)}`);
    return lead + gateBranch(core) + trail;
  }).join(',');
}

/** Index of the `}` matching the `{` at s[open]; strings and comments skipped. Calls onNested(i) for a `{`
 *  found at depth 1 (if given) — used to reject nesting inside style rules. */
function matchBrace(s, open, onNested) {
  let depth = 0;
  for (let i = open; i < s.length;) {
    const ch = s[i];
    if (ch === '\\') { i += 2; continue; }
    if (ch === '"' || ch === "'") { i = skipString(s, i); continue; }
    if (ch === '/' && s[i + 1] === '*') { i = skipComment(s, i); continue; }
    if (ch === 'u' || ch === 'U') { const e = skipUrl(s, i); if (e > 0) { i = e; continue; } }
    if (ch === '{') { if (depth === 1 && onNested) onNested(i); depth++; }
    else if (ch === '}' && --depth === 0) return i;
    i++;
  }
  throw new Error(`unbalanced braces: block opened at ${open} is never closed`);
}

/** Walk a block of statements s[from, to). visit(kind, data) for style rules; returns rewritten text. */
function walk(s, from, to, atRules, onRule) {
  let out = '';
  let i = from;
  while (i < to) {
    const ch = s[i];
    if (/\s/.test(ch)) { out += ch; i++; continue; }
    if (ch === '/' && s[i + 1] === '*') { const e = skipComment(s, i); out += s.slice(i, e); i = e; continue; }
    if (ch === '}') throw new Error(`unbalanced braces: unexpected } at ${i}`);
    // prelude up to { or ;
    let j = i, depth = 0;
    for (; j < to; j++) {
      const c = s[j];
      if (c === '\\') { j++; continue; }
      if (c === '"' || c === "'") { j = skipString(s, j) - 1; continue; }
      if (c === '/' && s[j + 1] === '*') { j = skipComment(s, j) - 1; continue; }
      if (c === '(' || c === '[') depth++;
      else if (c === ')' || c === ']') depth--;
      else if (depth === 0 && (c === '{' || c === ';' || c === '}')) break;
    }
    if (j >= to) throw new Error(`unterminated rule at ${i}: ${JSON.stringify(s.slice(i, i + 40))}`);
    const prelude = s.slice(i, j);
    if (s[j] === '}') throw new Error(`unbalanced braces near ${i}`);
    if (prelude.startsWith('@')) {
      const name = /^@([-\w]+)/.exec(prelude)?.[1]?.toLowerCase() || '';
      if (name === 'import') throw new Error('@import not supported: the imported sheet would not be gated');
      if (s[j] === ';') { out += s.slice(i, j + 1); i = j + 1; continue; }
      const close = matchBrace(s, j);
      if (GROUPING.has(name)) {
        out += prelude + '{' + walk(s, j + 1, close, [...atRules, prelude.trim()], onRule) + '}';
      } else if (OPAQUE.has(name)) {
        out += s.slice(i, close + 1);
      } else throw new Error(`unsupported block at-rule @${name}`);
      i = close + 1;
      continue;
    }
    if (s[j] === ';') throw new Error(`stray declaration outside a rule at ${i}: ${JSON.stringify(prelude.trim())}`);
    const close = matchBrace(s, j, at => { throw new Error(`nested rule inside a style rule at ${at} not supported`); });
    const body = s.slice(j + 1, close);
    const selector = prelude;
    out += onRule({selector, body, atRules}) + '{' + body + '}';
    i = close + 1;
  }
  return out;
}

/** Style rules in source order: {selector (trimmed), body, atRules[]} (used by tests). */
export function parseRules(css) {
  const rules = [];
  walk(css, 0, css.length, [], r => { rules.push({selector: r.selector.trim(), body: r.body, atRules: r.atRules}); return r.selector; });
  return rules;
}

/** Gate every style rule's selector; everything else is copied byte-for-byte. */
export function gateCss(css) {
  return walk(css, 0, css.length, [], r => gateSelector(r.selector));
}

export function renderOutput(original) { return HEADER + gateCss(original); }

/** Gated output for one sheet entry ({source, output, note}). */
export function renderSheet(sheet) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  return headerFor(sheet) + gateCss(fs.readFileSync(path.join(root, sheet.source), 'utf8'));
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const sheet of SHEETS) {
    const expected = headerFor(sheet) + gateCss(fs.readFileSync(path.join(root, sheet.source), 'utf8'));
    const target = path.join(root, sheet.output);
    if (check) {
      const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
      if (actual !== expected) { console.error(`${sheet.output} is stale or missing; run node scripts/gate-kb-css.mjs`); stale++; }
      else console.log(`gate:kb check ok (${sheet.output})`);
    } else {
      fs.mkdirSync(path.dirname(target), {recursive: true});
      fs.writeFileSync(target, expected);
      console.log(`wrote ${sheet.output} (${parseRules(expected).length} rules)`);
    }
  }
  if (stale) process.exit(1);
}
